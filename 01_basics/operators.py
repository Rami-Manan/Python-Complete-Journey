"""Practice: arithmetic and comparison operators."""

a = 12
b = 5

# Arithmetic operators
print("a + b =", a + b)
print("a - b =", a - b)
print("a * b =", a * b)
print("a / b =", a / b)
print("a % b =", a % b)

# Comparison operators
print("a > b:", a > b)
print("a == b:", a == b)
print("a != b:", a != b)
