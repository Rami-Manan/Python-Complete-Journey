"""Practice: variables and data types."""

# A variable stores data in memory.
name = "Rami"
age = 21
height = 1.73
is_student = True

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is student:", is_student)

# type() shows the data type of a variable.
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))
